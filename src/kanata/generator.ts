import type { KeyboardConfig, KeyboardLayer, KeyAction } from "./types";

/**
 * Generates a Kanata .kbd configuration file from a KeyboardConfig object.
 */
export function generateKanataConfig(config: KeyboardConfig): string {
  const lines: string[] = [];

  // Add header comment
  lines.push(";; Generated by Kanata UI");
  lines.push(";; Do not edit manually - changes will be overwritten");
  lines.push("");

  // Generate (defsrc) block
  lines.push(generateDefsrc(config.sourceKeys));
  lines.push("");

  // Generate aliases if present
  if (config.aliases && Object.keys(config.aliases).length > 0) {
    lines.push(generateDefalias(config.aliases));
    lines.push("");
  }

  // Generate each layer
  for (const layer of config.layers) {
    lines.push(generateDeflayer(layer, config.sourceKeys));
    lines.push("");
  }

  return lines.join("\n");
}

/**
 * Generates the (defsrc) block which defines the physical key layout.
 */
function generateDefsrc(sourceKeys: string[]): string {
  const formattedKeys = formatKeysInRows(sourceKeys);
  return `(defsrc\n${formattedKeys}\n)`;
}

/**
 * Generates a (deflayer) block for a single layer.
 */
function generateDeflayer(layer: KeyboardLayer, sourceKeys: string[]): string {
  // Map source keys to their actions in this layer
  const actions = sourceKeys.map((key) => layer.keys[key] ?? "_");
  const formattedActions = formatKeysInRows(actions);
  return `(deflayer ${layer.name}\n${formattedActions}\n)`;
}

/**
 * Generates a (defalias) block for complex key actions.
 */
function generateDefalias(aliases: Record<string, string>): string {
  const aliasLines = Object.entries(aliases)
    .map(([name, action]) => `  ${name} ${action}`)
    .join("\n");
  return `(defalias\n${aliasLines}\n)`;
}

/**
 * Formats an array of keys into rows for readability.
 * Attempts to group keys logically (number row, letter rows, etc.)
 */
function formatKeysInRows(keys: string[]): string {
  // Standard row lengths for a typical keyboard layout
  const rowLengths = [14, 14, 13, 12, 7]; // Adjust based on your source keys
  const rows: string[][] = [];

  let index = 0;
  for (const length of rowLengths) {
    if (index >= keys.length) break;
    const row = keys.slice(index, index + length);
    rows.push(row);
    index += length;
  }

  // Handle any remaining keys
  if (index < keys.length) {
    rows.push(keys.slice(index));
  }

  // Pad each key to align columns nicely
  return rows
    .map((row) => "  " + row.map((k) => padKey(k)).join(" "))
    .join("\n");
}

/**
 * Pads a key string to a minimum width for alignment.
 */
function padKey(key: string, minWidth = 4): string {
  return key.padEnd(minWidth);
}

/**
 * Converts a KeyAction object to its Kanata string representation.
 */
export function actionToString(action: KeyAction): string {
  if (typeof action === "string") {
    return action;
  }

  switch (action.type) {
    case "tap-hold": {
      const timeout = action.timeout ?? 200;
      return `(tap-hold ${timeout} ${timeout} ${action.tap} ${action.hold})`;
    }
    case "multi-tap": {
      const timeout = action.timeout ?? 200;
      const taps = action.taps.join(` ${timeout} `);
      return `(multi-tap ${timeout} ${taps})`;
    }
    case "remap":
      return action.key;
    case "layer":
      switch (action.mode) {
        case "momentary":
          return `(layer-while-held ${action.layer})`;
        case "toggle":
          return `(layer-toggle ${action.layer})`;
        case "one-shot":
          return `(one-shot ${action.layer})`;
      }
  }
}

/**
 * Creates a tap-hold alias string.
 * Example: (tap-hold 200 200 esc lctl)
 */
export function createTapHold(
  tap: string,
  hold: string,
  timeout = 200
): string {
  return `(tap-hold ${timeout} ${timeout} ${tap} ${hold})`;
}

/**
 * Creates a layer-while-held action string.
 */
export function createLayerHold(layerName: string): string {
  return `(layer-while-held ${layerName})`;
}

/**
 * Creates a layer-toggle action string.
 */
export function createLayerToggle(layerName: string): string {
  return `(layer-toggle ${layerName})`;
}

